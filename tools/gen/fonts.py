#!/usr/bin/env python3
"""Self-host the Inter font and write preview/fonts.css.

Inter ships as a variable font, so one file per unicode subset covers every
weight from 100 to 900. We keep only the subsets this site can render:
greek, greek-ext, latin, latin-ext.

Two reasons to host it ourselves instead of linking fonts.googleapis.com:
  * the third-party stylesheet is render-blocking, and on a cold cache it
    cost ~1.9 s before the first paint;
  * loading a font from Google sends the visitor's IP to a US provider, which
    German courts have ruled a GDPR violation. Not worth the risk on an EU
    rental site.

Usage:  python3 tools/gen/fonts.py
"""
import os
import re
import shutil
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PREVIEW = os.path.join(ROOT, "preview")
FONT_DIR = os.path.join(PREVIEW, "fonts")

CSS_URL = ("https://fonts.googleapis.com/css2"
           "?family=Inter:wght@400;500;600;700&display=swap")
# The UA decides which format Google serves; without a modern one it hands
# back legacy ttf instead of woff2.
UA = {"User-Agent": ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                     "AppleWebKit/537.36 (KHTML, like Gecko) "
                     "Chrome/120.0.0.0 Safari/537.36")}

KEEP = ("greek-ext", "greek", "latin-ext", "latin")
# One file covers 100-900, so we only need the first @font-face per subset.
WEIGHT_RANGE = "100 900"

HEADER = """/* Inter, self-hosted (generated by tools/gen/fonts.py).
   The variable font covers weights 100-900, so a single file per subset is
   enough. Serving it from this domain avoids a render-blocking request to
   fonts.googleapis.com and stops us sending visitor IPs to Google. */
"""


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def main():
    print("  fetching %s" % CSS_URL)
    css = fetch(CSS_URL).decode("utf-8")

    blocks = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css)
    if not blocks:
        sys.exit("  no @font-face blocks found - did Google change the format?")

    os.makedirs(FONT_DIR, exist_ok=True)
    rules, done, total = [], set(), 0

    for subset, block in blocks:
        if subset not in KEEP or subset in done:
            continue
        done.add(subset)
        match = re.search(r"url\((https://fonts\.gstatic\.com/[^)]+)\)", block)
        if not match:
            continue

        name = "inter-%s.woff2" % subset
        dest = os.path.join(FONT_DIR, name)
        data = fetch(match.group(1))
        with open(dest, "wb") as fh:
            fh.write(data)
        total += len(data)
        print("    %-22s %6.1f KB" % (name, len(data) / 1024))

        unicode_range = re.search(r"unicode-range:\s*([^;]+);", block)
        rule = ["@font-face {",
                "  font-family: 'Inter';",
                "  font-style: normal;",
                "  font-weight: %s;" % WEIGHT_RANGE,
                "  font-display: swap;",
                "  src: url(fonts/%s) format('woff2');" % name]
        if unicode_range:
            rule.append("  unicode-range: %s;" % unicode_range.group(1).strip())
        rule.append("}")
        rules.append("\n".join(rule))

    missing = [s for s in KEEP if s not in done]
    if missing:
        print("  ! subsets not served by Google: %s" % ", ".join(missing))

    out = os.path.join(PREVIEW, "fonts.css")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(HEADER + "\n" + "\n\n".join(rules) + "\n")

    print("  wrote preview/fonts.css  (%d subsets, %.1f KB)" % (len(rules), total / 1024))


if __name__ == "__main__":
    main()
